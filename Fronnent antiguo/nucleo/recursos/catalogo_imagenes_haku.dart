  /// Imagen principal de un lugar (prefiere local sobre red).
  static String imagenLugar({
    required String lugarId,
    required String provincia,
    String? fallback,
    CategoriaLugar? categoria,
  }) {
    if (categoria != null) {
      return imagenParaLugar(
        lugarId: lugarId,
        provincia: provincia,
        categoria: categoria,
        fallback: fallback,
      );
    }
    if (fallback != null && esLocal(fallback)) return fallback;
    return imagenDescubiertoComunidad(lugarId: lugarId, provincia: provincia);
  }

  /// Resuelve imagen según categoría del lugar.
  static String imagenParaLugar({
    required String lugarId,
    required String provincia,
    required CategoriaLugar categoria,
    String? fallback,
  }) {
    switch (categoria) {
      case CategoriaLugar.gastronomia:
        return imagenFogones(lugarId: lugarId, fallback: fallback);
      case CategoriaLugar.misterioso:
      case CategoriaLugar.magico:
        return imagenCuscoMagico(lugarId: lugarId, fallback: fallback);
      default:
        if (fallback != null && esLocal(fallback)) return fallback;
        return imagenDescubiertoComunidad(
          lugarId: lugarId,
          provincia: provincia,
        );
    }
  }

